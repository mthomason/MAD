	NSURL *directory = [NSURL fileURLWithPath:path isDirectory:YES];
	[[NSFileManager defaultManager] createDirectoryAtURL:directory
							 withIntermediateDirectories:YES
											  attributes:nil
												   error:nil];
	return directory;
}

// The version-1 store has to be built without the code under test, and
// user_version is read straight from SQLite, so nothing under test answers
// the question.
static BOOL SQLiteExecute(NSURL *url, NSString *sql) {
	sqlite3 *database = NULL;
	if (sqlite3_open([url.path fileSystemRepresentation], &database) != SQLITE_OK) return NO;
	char *message = NULL;
	int result = sqlite3_exec(database, [sql UTF8String], NULL, NULL, &message);
	if (message) sqlite3_free(message);
	sqlite3_close(database);
	return result == SQLITE_OK;
}

static NSInteger SQLiteUserVersion(NSURL *url) {
	sqlite3 *database = NULL;
	if (sqlite3_open([url.path fileSystemRepresentation], &database) != SQLITE_OK) return -1;
	sqlite3_stmt *statement = NULL;
	NSInteger version = 0;
	if (sqlite3_prepare_v2(database, "PRAGMA user_version;", -1, &statement, NULL) == SQLITE_OK) {
		if (sqlite3_step(statement) == SQLITE_ROW) version = (NSInteger)sqlite3_column_int64(statement, 0);
	}
	sqlite3_finalize(statement);
	sqlite3_close(database);
	return version;
}

static BOOL SQLiteTableHasColumn(NSURL *url, NSString *table, NSString *column) {
	sqlite3 *database = NULL;
	if (sqlite3_open([url.path fileSystemRepresentation], &database) != SQLITE_OK) return NO;
	NSString *sql = [[NSString alloc] initWithFormat:@"PRAGMA table_info(\"%@\");", table];
	sqlite3_stmt *statement = NULL;
	BOOL found = NO;
	if (sqlite3_prepare_v2(database, [sql UTF8String], -1, &statement, NULL) == SQLITE_OK) {
		while (sqlite3_step(statement) == SQLITE_ROW) {
			const unsigned char *name = sqlite3_column_text(statement, 1);
			if (name != NULL && strcmp((const char *)name, [column UTF8String]) == 0) { found = YES; break; }
		}
	}
	sqlite3_finalize(statement);
	sqlite3_close(database);
	return found;
}

static NSURL *makeVersionOneStoreURL(NSURL *directory) {
	NSURL *url = [directory URLByAppendingPathComponent:@"definition.sqlite"];
	MAD_PASS((SQLiteExecute(url, MADVersionOneSchemaSQL)), "the version-1 schema failed to execute");
	MAD_PASS((SQLiteExecute(url, MADVersionOneRowsSQL)), "the version-1 rows failed to execute");
	return url;
}

static void testVersionOneStoreMigratesOnOpen(void) {
	NSURL *directory = makeTempDirectory();
	NSURL *url = makeVersionOneStoreURL(directory);

	MADStore *store = [MADStore storeWithURL:url];
	NSError *error = nil;
	MAD_PASS([store openWithError:&error], "open failed: %s", [[error description] UTF8String]);

	MAD_PASS((SQLiteTableHasColumn(url, @"RptqQuery", @"sqlSourceText")), "RptqQuery did not gain sqlSourceText");
	MAD_PASS(SQLiteUserVersion(url) == MADStoreCurrentVersion, "user_version");

	MADStoreGraph *graph = [store allObjectsWithError:&error];
	MAD_PASS(graph != nil, "read failed: %s", [[error description] UTF8String]);
	if (graph == nil) {
		[store close];
		[[NSFileManager defaultManager] removeItemAtURL:directory error:nil];
		return;
	}
	MAD_PASS(graph.count == (NSUInteger)15, "every version-1 row survives");

	MADStoreObject *query = [graph objectForEntity:@"RptqQuery" identifier:20];
	MAD_PASS(query != nil, "the query row survives");
	MAD_PASS_EQUAL([query attributeValue:@"cachedText"], @"SELECT ...", "cachedText survives");
	MAD_PASS([query attributeValue:@"sqlSourceText"] == nil, "no text was stored in version 1");
	MAD_PASS_EQUAL([query referenceForName:@"inDatabase"], @10, "the query's database edge survives");

	MADStoreObject *table = [graph objectForEntity:@"RptqDatabaseSchemaTable" identifier:11];
	MAD_PASS_EQUAL([table existingCollectionForName:@"hasFields"], (@[ @13, @14, @12 ]), "the ordered fields survive in order");

	MADStoreObject *field = [graph objectForEntity:@"RptqDatabaseSchemaField" identifier:13];
	MAD_PASS_EQUAL([field attributeValue:@"name"], @"name", "the field row survives");
	MAD_PASS_EQUAL([field referenceForName:@"inTable"], @11, "the field's table edge survives");

	MADStoreObject *queryTable = [graph objectForEntity:@"RptqQueryTable" identifier:21];
	MAD_PASS_EQUAL([queryTable attributeValue:@"alias"], @"c", "the query table survives");
	MAD_PASS_EQUAL([queryTable referenceForName:@"databaseSchemaTable"], @11, "the query table's schema edge survives");

	MAD_PASS_EQUAL([query existingCollectionForName:@"hasFields"], (@[ @12, @13 ]), "the many-to-many edge survives");
	MADStoreObject *idField = [graph objectForEntity:@"RptqDatabaseSchemaField" identifier:12];
	MAD_PASS_EQUAL([idField existingCollectionForName:@"inQuery"], (@[ @20 ]), "the many-to-many inverse survives");
	MADStoreObject *emailField = [graph objectForEntity:@"RptqDatabaseSchemaField" identifier:14];
	MAD_PASS([emailField existingCollectionForName:@"inQuery"].count == (NSUInteger)0, "the unselected field stays out of the join table");

	MADStoreObject *detail = [graph objectForEntity:@"RptqDocumentSection" identifier:30];
	MAD_PASS_EQUAL([detail existingCollectionForName:@"hasRows"], (@[ @41, @40 ]), "the ordered rows survive in order");

	MADStoreObject *label = [graph objectForEntity:@"RptqDocumentElementLabel" identifier:50];
	MAD_PASS_EQUAL([label attributeValue:@"text"], @"Hello, world", "the element row survives");
	MAD_PASS_EQUAL([label attributeValue:@"fontsize"], @12.5, "the element's attributes survive");

	[store close];
	[[NSFileManager defaultManager] removeItemAtURL:directory error:nil];
}

static void testOpeningTwiceIsIdempotent(void) {
	NSURL *directory = makeTempDirectory();
	NSURL *url = makeVersionOneStoreURL(directory);

	MADStore *first = [MADStore storeWithURL:url];
	NSError *error = nil;
	MAD_PASS([first openWithError:&error], "first open failed: %s", [[error description] UTF8String]);
	MAD_PASS(SQLiteUserVersion(url) == MADStoreCurrentVersion, "user_version after the first open");
	NSUInteger countAfterFirst = [first allObjectsWithError:&error].count;
	[first close];

	MADStore *second = [MADStore storeWithURL:url];
	MAD_PASS([second openWithError:&error], "second open failed: %s", [[error description] UTF8String]);
	MAD_PASS(SQLiteUserVersion(url) == MADStoreCurrentVersion, "user_version after the second open");
	NSUInteger countAfterSecond = [second allObjectsWithError:&error].count;
	MAD_PASS(countAfterSecond == countAfterFirst, "the second open changes no row");
	MAD_PASS((SQLiteTableHasColumn(url, @"RptqQuery", @"sqlSourceText")), "the column survives the second open");
	[second close];
	[[NSFileManager defaultManager] removeItemAtURL:directory error:nil];
}

static void testFreshStoreIsCreatedAtTheCurrentVersion(void) {
	NSURL *directory = makeTempDirectory();
	NSURL *url = [directory URLByAppendingPathComponent:@"fresh.sqlite"];
	MAD_PASS(![[NSFileManager defaultManager] fileExistsAtPath:[url path]], "the fresh URL does not exist yet");

	MADStore *store = [MADStore storeWithURL:url];
	NSError *error = nil;
	MAD_PASS([store openWithError:&error], "open failed: %s", [[error description] UTF8String]);

	MAD_PASS(SQLiteUserVersion(url) == MADStoreCurrentVersion, "a fresh store is born at the current version");
	MAD_PASS((SQLiteTableHasColumn(url, @"RptqQuery", @"sqlSourceText")), "createSchemaSQL carries the column");
	[store close];
	[[NSFileManager defaultManager] removeItemAtURL:directory error:nil];
}

// The migrated column is a working column, not a hole the reader skips:
// writing the attribute and reading it back round-trips.
static void testMigratedStoreCarriesTheNewAttribute(void) {
	NSURL *directory = makeTempDirectory();
	NSURL *url = makeVersionOneStoreURL(directory);

	MADStore *store = [MADStore storeWithURL:url];
	NSError *error = nil;
	MAD_PASS([store openWithError:&error], "open failed: %s", [[error description] UTF8String]);

	MADStoreObject *query = [store objectForEntity:@"RptqQuery" identifier:20 error:&error];
	MAD_PASS(query != nil, "the query row survives");
	[query setAttributeValue:@"SELECT * FROM customers -- entered by hand" forName:@"sqlSourceText"];
	MAD_PASS([store writeObject:query error:&error], "write failed: %s", [[error description] UTF8String]);

	MADStoreObject *reread = [store objectForEntity:@"RptqQuery" identifier:20 error:&error];
	MAD_PASS_EQUAL([reread attributeValue:@"sqlSourceText"], @"SELECT * FROM customers -- entered by hand", "the new column round-trips");
	[store close];
	[[NSFileManager defaultManager] removeItemAtURL:directory error:nil];
}

