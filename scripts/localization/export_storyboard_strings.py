"""Export the Base.lproj storyboard and xib strings as UTF-8 .strings files.

This is the macOS-only half of the storyboard workflow: ibtool reads the
compiled interface files, and this script normalizes its UTF-16 output to
UTF-8, writes it under scripts/localization/storyboard_strings/, and marks the
entries that must not be translated.  It runs neither in CI nor on Linux.

	python3 -I scripts/localization/export_storyboard_strings.py

The exported tree is the English source for review and translation handoff.
A translation is added to the project by creating <lang>.lproj/<Name>.strings
next to the Base.lproj resource and adding it to the storyboard's variant
group; see storyboard_strings/README.md.
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT = Path(__file__).resolve().parent / "storyboard_strings"

# The app's resources and the three live driver framework copies.  MADAPI's
# MADCreateDocument copy is dead (no code loads the MADAPI bundle) and is not
# exported.
RESOURCE_DIRS = (
	("MADDesigner/Resources/Storyboard/Base.lproj", "MADDesigner/Storyboard"),
	("MADDesigner/Resources/Nibs/Base.lproj", "MADDesigner/Nibs"),
	("MADMySQL/Resources/Base.lproj", "MADMySQL"),
	("MADPostgres/Resources/Base.lproj", "MADPostgres"),
	("MADTdsClient/Resources/Base.lproj", "MADTdsClient"),
)

BRANDS = (
	"MAD", "MAD Designer", "MAD Viewer", "MAD Query", "MAD Barcodes",
	"SQL", "MySQL",
	"MariaDB", "PostgreSQL", "SQL Server", "Microsoft SQL Server", "SQLite",
	"iCloud", "GitHub",
)

# Design-time values the interface builder needed to lay the screen out.  They
# are not copy: the runtime replaces them or leaves them as placeholders.
PLACEHOLDERS = frozenset({
	"Item", "Title", "Detail", "Subtitle", "Body", "Sample", "Sample data",
})

BARCODE_SOURCE = ROOT / "MADBarcodes/MADBarcodes/MADBarcodes/MADBarcode.m"
BARCODE_VALUE_RE = re.compile(r'@BARCODE_\w+\s*:\s*@"((?:[^"\\]|\\.)*)"')
BARCODE_TECHNICAL_RE = re.compile(
	r"^(?:"
	r">?\s*\d+%|"
	r"\d+\s*[x×]\s*\d+|"
	r"\d+\s*Words|"
	r"\d+[xX]\s*height|"
	r"Mod-\d+|"
	r"[A-Z]{2,3}-[A-Z0-9]+.*|"
	r"Approximately\s+\d+%"
	r")"
)
FONT_NAMES = frozenset({
	"Avenir", "Avenir Next", "Courier", "Courier New", "Georgia", "Helvetica",
	"Helvetica Neue", "Menlo", "Times New Roman", "Trebuchet", "Trebuchet MS",
})
LOCALE_CODES = frozenset({
	"ar", "cs", "da", "de", "el", "en", "es", "fi", "fr", "he", "hi", "hu",
	"id", "it", "ja", "ko", "ms", "nl", "no", "pl", "pt", "pt-BR", "ro", "ru",
	"sk", "sv", "th", "tr", "uk", "vi", "zh", "zh-Hans", "zh-Hant",
})
SAMPLE_SIZE_RE = re.compile(r"^\d[\d.,]*\s*(?:KB|MB|GB|TB)$")
ENTRY_RE = re.compile(r'^"(?P<key>(?:[^"\\]|\\.)*)"\s*=\s*"(?P<value>(?:[^"\\]|\\.)*)";\s*$')


def barcode_names():
	"""Return the barcode display names, read from the framework's own table."""
	if not BARCODE_SOURCE.is_file():
		return set()
	text = BARCODE_SOURCE.read_text(encoding="utf-8", errors="replace")
	return set(BARCODE_VALUE_RE.findall(text))


def do_not_translate_reason(value, names):
	if not re.search(r"[A-Za-z]", value):
		return "numeric or symbolic value."
	if len(value) == 1:
		return "one-letter interface abbreviation."
	if value in BRANDS:
		return "product or brand name."
	if value in FONT_NAMES:
		return "font name; a technical identifier."
	if value in LOCALE_CODES:
		return "locale identifier."
	if value in PLACEHOLDERS:
		return "design-time placeholder."
	if value.startswith("Lorem ipsum"):
		return "design-time placeholder text."
	if SAMPLE_SIZE_RE.match(value):
		return "sample value."
	if value in names:
		return "barcode symbology name; a standard or product name."
	if BARCODE_TECHNICAL_RE.match(value):
		return "barcode technical value."
	return None


def export(source, output, names):
	with tempfile.TemporaryDirectory() as directory:
		temporary = Path(directory) / "strings"
		completed = subprocess.run(
			["xcrun", "ibtool", "--export-strings-file", str(temporary), str(source)],
			capture_output=True, text=True,
		)
		if completed.returncode != 0:
			raise SystemExit("ibtool failed for %s:\n%s" % (source, completed.stderr))
		raw = temporary.read_bytes()
	text = raw.decode("utf-16") if raw[:2] in (b"\xff\xfe", b"\xfe\xff") else raw.decode("utf-8")

	header = (
		"/*\n"
		"  %s — strings exported from %s.\n"
		"  Generated by scripts/localization/export_storyboard_strings.py; do not edit by hand.\n"
		"  Entries marked DO NOT TRANSLATE keep the English source verbatim.\n"
		"  Add a translation in <lang>.lproj/%s as translations arrive.\n"
		"*/\n" % (output.name, source.relative_to(ROOT).as_posix(),
				  output.with_suffix(".strings").name)
	)
	lines = [header]
	marked = 0
	for line in text.splitlines():
		lines.append(line)
		match = ENTRY_RE.match(line)
		if not match:
			continue
		reason = do_not_translate_reason(match.group("value"), names)
		if reason:
			lines.append("/* DO NOT TRANSLATE: %s */" % reason)
			marked += 1
	output.parent.mkdir(parents=True, exist_ok=True)
	output.write_text("\n".join(lines).rstrip() + "\n", encoding="utf-8")
	return marked


def main():
	names = barcode_names()
	total = 0
	marked_total = 0
	for relative, destination in RESOURCE_DIRS:
		base = ROOT / relative
		if not base.is_dir():
			continue
		for source in sorted(base.iterdir()):
			if source.suffix not in (".storyboard", ".xib"):
				continue
			output = OUTPUT / destination / (source.stem + ".strings")
			marked = export(source, output, names)
			entries = sum(1 for line in output.read_text(encoding="utf-8").splitlines()
						  if ENTRY_RE.match(line))
			total += entries
			marked_total += marked
			print("%-55s %4d entries, %3d marked" % (
				source.relative_to(ROOT).as_posix(), entries, marked))
	print("")
	print("Exported %d entries, %d marked DO NOT TRANSLATE." % (total, marked_total))
	return 0


if __name__ == "__main__":
	sys.exit(main())
